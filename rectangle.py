def area(a, b): 
    '''
    Считает площадь прямоугольника
        Принимает:
            a (int): первая сторона прямоугольника
            b (int): вторая сторона прямоугольника
        Возвращает:
            s (int): площадь прямоугольника
    '''
    return a * b 

def perimeter(a, b): 
    '''
    Считает периметр прямоугольника
        Принимает:
            a (int): первая сторона прямоугольника
            b (int): вторая сторона прямоугольника
        Возвращает:
            p (int): периметр прямоугольника
    '''
    return (a + b) * 2