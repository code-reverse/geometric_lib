import math


def area(r):
    '''
    Считает площадь окружности
        Принимает:
            r (int): радиус окружности
        Возвращает: 
            s (float): площадь окружности
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Считает длинну окружности
        Принимает:
            r (int): радиус окружности
        Возвращает: 
            p (float): длинну окружности
    '''
    return 2 * math.pi * r

